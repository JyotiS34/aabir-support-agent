// Merge the cached sentiment (from the fine-tuned aabir-sentiment-v1 model)
// into each cached analysis, exactly as the live agent does. This keeps the
// Inbox + Analytics rendering instant while still showing the sentiment signal.
export const CACHED_ANALYSES: Record<string, AgentAnalysis> = Object.fromEntries(
  Object.entries(RAW_ANALYSES).map(([id, analysis]) => {
    const sentiment = CACHED_SENTIMENTS[id] ?? null;
    const signals = [...analysis.escalationSignals];
    if (sentiment && sentiment.escalationWeight >= 0.4) {
      signals.push(`Sentiment "${sentiment.label}" (intensity ${Math.round(sentiment.intensity * 100)}%) from aabir-sentiment-v1`);
    }
    return [
      id,
      {
        ...analysis,
        sentiment: sentiment
          ? { ...sentiment, latencyMs: 100, modelId: "aabir-sentiment-v1" }
          : null,
        escalationSignals: signals,
      },
    ];
  }),
);

